      const tiles = $$(".tile:not(.empty):not(.insufficient)", $("#tile-map"));
      const idx = tiles.indexOf(tile);
      const cols = state.dim === "state" ? 12 : Math.max(1, Math.round($("#tile-map").clientWidth / 80));
