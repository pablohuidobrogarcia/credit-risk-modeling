function nearestIndex(values, target) {
  let best = 0; let bestDiff = Infinity;
  values.forEach((value, index) => {
    const diff = Math.abs(Number(value) - Number(target));
    if (diff < bestDiff) { best = index; bestDiff = diff; }
  });
  return best;
}
