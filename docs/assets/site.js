const countCache = new Map();
function countUp(el, value, formatter) {
  if (!el) return;
  const target = num(value);
  if (target == null) { el.textContent = "—"; return; }
  const key = el.getAttribute("data-testid") || el.id || "";
  const raw = String(el.dataset.raw || "");
  const nextRaw = String(target);
  if (raw === nextRaw) { el.textContent = formatter(target); return; }
  el.dataset.raw = nextRaw;
  if (prefersReduced()) { el.textContent = formatter(target); countCache.set(key, target); return; }
  const cached = countCache.get(key);
  const start = cached != null ? cached : Number(el.dataset.shown || 0);
  const from = Number.isFinite(start) ? start : 0;
  el.textContent = formatter(from);
  const t0 = performance.now();
  const duration = 520;
  const step = (now) => {
    const t = clamp((now - t0) / duration, 0, 1);
    const eased = 1 - Math.pow(1 - t, 3);
    const current = from + (target - from) * eased;
    el.textContent = formatter(current);
    el.dataset.shown = String(current);
    if (t < 1) requestAnimationFrame(step);
    else { el.textContent = formatter(target); el.dataset.shown = nextRaw; countCache.set(key, target); }
  };
  requestAnimationFrame(step);
}

/* ---------------------------------------------------------------- colors */
function hexToRgb(hex) {
  const h = hex.replace("#", "");
  const full = h.length === 3 ? h.split("").map((c) => c + c).join("") : h;
  const int = parseInt(full, 16);
  return [(int >> 16) & 255, (int >> 8) & 255, int & 255];
}
function mix(a, b, t) {
  const A = hexToRgb(a); const B = hexToRgb(b);
  return `rgb(${Math.round(A[0] + (B[0] - A[0]) * t)}, ${Math.round(A[1] + (B[1] - A[1]) * t)}, ${Math.round(A[2] + (B[2] - A[2]) * t)})`;
}
function scaleColor(t) {
  const stops = [[0, "#0f766e"], [0.5, "#eab308"], [1, "#b91c1c"]];
  if (t <= 0.5) return mix(stops[0][1], stops[1][1], t / 0.5);
  return mix(stops[1][1], stops[2][1], (t - 0.5) / 0.5);
}
function colorFor(value, lo, hi) {
  if (num(value) == null || !Number.isFinite(lo) || !Number.isFinite(hi) || hi <= lo) return "#64748b";
  return scaleColor(clamp((value - lo) / (hi - lo), 0, 1));
}
function readableText(background) {
  const match = background.match(/\d+/g);
  if (!match) return "#fff";
  const [r, g, b] = match.map(Number);
  const luminance = (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  return luminance > 0.62 ? "#111827" : "#ffffff";
}

