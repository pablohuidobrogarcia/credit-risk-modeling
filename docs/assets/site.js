async function boot() {
  try {
    const response = await fetch(DATA_URL, { cache: "no-cache" });
    if (!response.ok) throw new Error(`data.json ${response.status}`);
    D = await response.json();
    if (!D.portfolio_explorer) throw new Error("data.json has no portfolio_explorer block");
    readHash();
    applyHashState();
    $("#app-skeleton").hidden = true;
    $("#app-content").hidden = false;
    bindDrawer();
    $("#theme-toggle").onclick = cycleTheme;
    applyTheme();
    setupRiskControls();
    setupSimulator();
    setupCutoff();
    paint();
    bindThemeMedia();
    window.addEventListener("popstate", () => { readHash(); applyHashState(); paint(); });
    writeHash(false);
    loadPlotly().then(() => { paint(); }).catch((err) => {
      console.warn("Plotly unavailable:", err.message);
      paint();
    });
  } catch (err) {
    console.error("Could not load the dashboard:", err);
    $("#app-skeleton").hidden = true;
    const content = $("#app-content");
    if (content) content.hidden = false;
    const banner = $("#data-error");
    if (banner) banner.hidden = false;
    const hero = $("#hero-note-copy");
    if (hero) hero.textContent = "The dashboard data could not be loaded. Check that docs/data.json was generated by the pipeline.";
  }
}

