function renderScoreHist(host, hist, bins, caption, markerValue) {
  if (!host) return;
  if (!hist || !hist.length || !bins || bins.length < 2) { host.innerHTML = ""; return; }
  const max = Math.max(...hist, 1);
  const width = 320; const height = 74; const gap = 1.5;
  const barWidth = (width - gap * (hist.length - 1)) / hist.length;
  let svg = `<svg viewBox="0 0 ${width} ${height + 18}" preserveAspectRatio="none" aria-hidden="true">`;
  hist.forEach((count, i) => {
    const h = (count / max) * height;
    const x = i * (barWidth + gap);
    const y = height - h;
    svg += `<rect class="bar" x="${x.toFixed(2)}" y="${y.toFixed(2)}" width="${barWidth.toFixed(2)}" height="${h.toFixed(2)}" rx="1.4"></rect>`;
  });
  if (num(markerValue) != null && bins.length) {
    const lo = bins[0]; const hi = bins[bins.length - 1];
    const x = clamp(((markerValue - lo) / (hi - lo || 1)) * width, 0, width);
    svg += `<line class="marker" x1="${x.toFixed(1)}" x2="${x.toFixed(1)}" y1="0" y2="${height}"></line>`;
  }
  svg += `<text x="0" y="${height + 14}">${Math.round(bins[0])}</text><text x="${width}" y="${height + 14}" text-anchor="end">${Math.round(bins[bins.length - 1])}</text>`;
  svg += "</svg>";
  host.innerHTML = svg;
  const fig = host.closest("figure");
  const cap = fig && fig.querySelector("figcaption");
  if (cap) cap.textContent = caption;
  const selCap = $("#score-hist-caption");
  if (selCap && host.id === "score-hist") selCap.textContent = caption;
}

