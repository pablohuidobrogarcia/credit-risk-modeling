function riskOptions() {
  const sc = D.interactive && D.interactive.scenario_explorer;
  if (!sc) return { rhos: [], pds: [], lgds: [] };
  return {
    rhos: unique(sc.scenarios.map((s) => s.rho)),
    pds: unique(sc.scenarios.map((s) => s.pd_mult)),
    lgds: unique(sc.scenarios.map((s) => s.lgd_mult)),
  };
}
function nearestIndex(values, target) {
  let best = 0; let bestDiff = Infinity;
  values.forEach((value, index) => {
    const diff = Math.abs(Number(value) - Number(target));
    if (diff < bestDiff) { best = index; bestDiff = diff; }
  });
  return best;
}
function scenarioForState() {
  const sc = D.interactive && D.interactive.scenario_explorer;
  if (!sc) return null;
  return sc.scenarios.find((s) => Math.abs(s.rho - state.risk.rho) < 1e-9 && Math.abs(s.pd_mult - state.risk.pd) < 1e-9 && Math.abs(s.lgd_mult - state.risk.lgd) < 1e-9) || sc.scenarios[0];
}
function scenarioNotation(scenario) {
  if (!scenario) return "-";
  return `ρ = ${fmtNum(scenario.rho, 2)} · PD ×${fmtNum(scenario.pd_mult, 2)} · LGD ×${fmtNum(scenario.lgd_mult, 2)}`;
}
