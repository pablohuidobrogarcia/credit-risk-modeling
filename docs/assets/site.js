function loadPlotly() {
  if (PLOTLY) return Promise.resolve(PLOTLY);
  if (plotlyTried) return Promise.reject(new Error("Plotly unavailable"));
  plotlyTried = true;
  return new Promise((resolve, reject) => {
    const script = document.createElement("script");
    script.src = PLOTLY_URL;
    script.async = true;
    script.integrity = PLOTLY_SRI;
    script.crossOrigin = "anonymous";
    script.onload = () => {
      if (window.Plotly) { PLOTLY = window.Plotly; resolve(PLOTLY); }
      else reject(new Error("Plotly did not expose window.Plotly"));
    };
    script.onerror = () => reject(new Error("Plotly failed to load"));
    document.head.appendChild(script);
  });
}
